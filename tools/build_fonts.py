#!/usr/bin/env python3
"""Generate original Tab5 Latin subsets from pinned LVGL Montserrat (OFL-1.1).

Uses isolated Node 22.12.0 + lv_font_conv 1.5.3; no font pixels enter app flash.
"""
import hashlib,json,subprocess,shutil
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def main():
 node=ROOT/'.tools/node-v22.12.0-darwin-arm64/bin/node'
 converter=ROOT/'.tools/font-conv/node_modules/lv_font_conv/lv_font_conv.js'
 font=ROOT/'managed_components/lvgl__lvgl/scripts/generators/built_in_font/Montserrat-Medium.ttf'
 output=ROOT/'sdcard/Tab5-Emu/assets/fonts';output.mkdir(parents=True,exist_ok=True)
 manifest={'format':'tab5-font-resources-v1','generator':'lv_font_conv@1.5.3','source_sha256':hashlib.sha256(font.read_bytes()).hexdigest(),'license':'OFL-1.1','fonts':[]}
 for size in (16,20,24,32):
  dest=output/f'tab5-latin-{size}.font'
  subprocess.run([str(node),str(converter),'--font',str(font),'--size',str(size),'--bpp','4','--format','bin','--range','0x20-0xFF,0x2026','--no-compress','--no-kerning','--output',str(dest)],check=True)
  data=dest.read_bytes();manifest['fonts'].append({'pixels':size,'file':dest.name,'bytes':len(data),'sha256':hashlib.sha256(data).hexdigest()})
 shutil.copyfile(font.parent/'font_license/Montserrat/OFL.txt',output/'OFL-Montserrat.txt')
 (output/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
 header=ROOT/'components/gui/include/font_resources.hpp'
 header.write_text('// Generated by tools/build_fonts.py. Asset identities only; glyphs stay on SD.\n#pragma once\n#include <cstddef>\nnamespace tab5::fonts {\nstruct Resource {const char *path;const char *sha256;size_t bytes;};\ninline constexpr Resource resources[]={\n'+''.join(' {"assets/fonts/%s","%s",%d},\n'%(f['file'],f['sha256'],f['bytes']) for f in manifest['fonts'])+'};\n}\n')
 print(json.dumps(manifest,indent=2))
if __name__=='__main__':main()
