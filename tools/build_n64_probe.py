"""Original MIPS III CPU test program; not a console boot ROM or game."""
from pathlib import Path
import struct,hashlib,json
ROOT=Path(__file__).resolve().parents[1]
def program():
 def i(op,rs,rt,imm):return (op<<26)|(rs<<21)|(rt<<16)|(imm&65535)
 def r(rs,rt,rd,sa,fn):return (rs<<21)|(rt<<16)|(rd<<11)|(sa<<6)|fn
 return [i(25,0,1,1),r(0,1,1,0,60),i(25,1,1,-1),r(0,1,2,16,56),i(25,0,3,-1),r(2,3,4,0,45),i(13,0,5,0x1234),i(15,0,8,0x8000),i(63,8,4,0x200),i(55,8,6,0x200),i(4,6,4,2),i(25,0,7,7),i(25,0,7,99),i(14,5,9,0xff),i(25,0,10,17),i(25,0,11,5),r(10,11,0,0,29),r(0,0,12,0,18),i(13,0,13,0xabc),i(17,4,13,0),i(17,0,14,0),i(25,0,0,123),13]
def main():
 data=b''.join(struct.pack('>I',op) for op in program());sha=hashlib.sha256(data).hexdigest()
 directory=ROOT/'artifacts/test-roms';directory.mkdir(parents=True,exist_ok=True)
 (directory/'tab5-n64-cpu-probe.mips').write_bytes(data)
 manifest={'license':'0BSD','kind':'bounded MIPS III CPU test, no boot code, graphics, audio or game','bytes':len(data),'sha256':sha,'words':len(program())}
 (directory/'n64-cpu-probe.json').write_text(json.dumps(manifest,indent=2)+'\n')
 header=ROOT/'experiments/n64/probe/fixture_identity.h';header.parent.mkdir(parents=True,exist_ok=True)
 header.write_text('// Generated by tools/build_n64_probe.py; no guest instructions embedded.\n#pragma once\n#define N64_PROBE_SHA256 "'+sha+'"\n#define N64_PROBE_BYTES '+str(len(data))+'\n')
 print(json.dumps(manifest,indent=2))
if __name__=='__main__':main()
